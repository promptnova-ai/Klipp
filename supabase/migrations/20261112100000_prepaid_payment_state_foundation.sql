-- Prepaid booking lifecycle foundation.
-- This is additive: existing booking creation and dispatch behavior is unchanged
-- until the dedicated checkout/creation RPC migration is deployed.

ALTER TYPE public.booking_status ADD VALUE IF NOT EXISTS 'payment_pending';

ALTER TABLE public.bookings
  ADD COLUMN IF NOT EXISTS payment_due_at timestamptz,
  ADD COLUMN IF NOT EXISTS price_locked_at timestamptz,
  ADD COLUMN IF NOT EXISTS dispatch_started_at timestamptz;

ALTER TABLE public.payments
  ADD COLUMN IF NOT EXISTS idempotency_key text,
  ADD COLUMN IF NOT EXISTS currency_code text NOT NULL DEFAULT 'DOP',
  ADD COLUMN IF NOT EXISTS checkout_expires_at timestamptz;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.payments'::regclass
      AND conname = 'payments_currency_code_dop'
  ) THEN
    ALTER TABLE public.payments
      ADD CONSTRAINT payments_currency_code_dop CHECK (currency_code = 'DOP');
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.payments'::regclass
      AND conname = 'payments_idempotency_key_length'
  ) THEN
    ALTER TABLE public.payments
      ADD CONSTRAINT payments_idempotency_key_length
      CHECK (idempotency_key IS NULL OR length(idempotency_key) BETWEEN 16 AND 128);
  END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS payments_idempotency_key_uidx
  ON public.payments (idempotency_key)
  WHERE idempotency_key IS NOT NULL;

COMMENT ON TYPE public.booking_status IS
  'Booking lifecycle. payment_pending means checkout has not been verified; requested means payment is verified and dispatch may begin.';

COMMENT ON COLUMN public.bookings.payment_due_at IS
  'Deadline for the client to complete the initial checkout; normally 10 minutes after booking creation.';
COMMENT ON COLUMN public.bookings.price_locked_at IS
  'Timestamp when the customer-facing price was frozen for checkout.';
COMMENT ON COLUMN public.bookings.dispatch_started_at IS
  'First time Klipp began professional dispatch after verified payment.';
COMMENT ON COLUMN public.payments.idempotency_key IS
  'Client checkout attempt idempotency token generated by trusted backend; unique across attempts.';
COMMENT ON COLUMN public.payments.currency_code IS
  'Currency used for the AZUL payment attempt. Klipp launches in Dominican pesos (DOP).';
COMMENT ON COLUMN public.payments.checkout_expires_at IS
  'Expiry of the hosted checkout attempt; expired attempts must not be accepted by a later callback.';
