create table if not exists public.service_equipment_requirements (
  id bigint generated by default as identity primary key,
  service_type_id integer not null references public.service_types(id) on delete cascade,
  item_name text not null,
  details text not null default '',
  required boolean not null default true,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint service_equipment_requirements_service_item_key unique (service_type_id, item_name)
);

alter table public.service_equipment_requirements enable row level security;
drop policy if exists service_equipment_requirements_public_read on public.service_equipment_requirements;
create policy service_equipment_requirements_public_read
  on public.service_equipment_requirements for select
  using (active is true);

create table if not exists public.pro_portfolio (
  id uuid primary key default gen_random_uuid(),
  pro_id uuid not null references public.pro_profiles(user_id) on delete cascade,
  object_path text not null unique,
  caption text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint pro_portfolio_sort_order_check check (sort_order >= 0)
);

create index if not exists pro_portfolio_pro_sort_idx
  on public.pro_portfolio(pro_id, sort_order, created_at desc);

alter table public.pro_portfolio enable row level security;
drop policy if exists pro_portfolio_public_read on public.pro_portfolio;
create policy pro_portfolio_public_read
  on public.pro_portfolio for select
  using (true);
drop policy if exists pro_portfolio_insert_own on public.pro_portfolio;
create policy pro_portfolio_insert_own
  on public.pro_portfolio for insert
  with check (pro_id = (select auth.uid()));
drop policy if exists pro_portfolio_update_own on public.pro_portfolio;
create policy pro_portfolio_update_own
  on public.pro_portfolio for update
  using (pro_id = (select auth.uid()))
  with check (pro_id = (select auth.uid()));
drop policy if exists pro_portfolio_delete_own on public.pro_portfolio;
create policy pro_portfolio_delete_own
  on public.pro_portfolio for delete
  using (pro_id = (select auth.uid()));

